// Writes supabase/seed.sql from the app's data files: `npm run seed:sql`.
import fs from "node:fs";
import path from "node:path";
import { getDistricts, STATES } from "../src/lib/content";

const q = (v: string | null) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(",")}]::text[]`;

let districtRows = 0;
const lines = ["-- Generated by scripts/seed-sql.ts. Do not edit by hand.", "begin;", "delete from districts;", "delete from states;"];
for (const s of STATES) {
  lines.push(
    `insert into states values (${q(s.id)}, ${s.lgd}, ${q(s.name)}, ${q(s.type)}, ${q(s.capital)}, ${q(s.region)}, ${arr(s.languages)}, ${s.districtCount}, ${arr(s.neighbours)}, ${q(s.dataStatus)}, ${q(`/data/districts/${s.id}.topo.json`)});`,
  );
}
for (const s of STATES) {
  for (const d of getDistricts(s.id)) {
    districtRows++;
    lines.push(
      `insert into districts values (${q(d.id)}, ${q(s.id)}, ${d.lgd}, ${q(d.name)}, ${q(d.lgdName)}, ${q(d.headquarters)}, ${q(d.fact)}, ${d.curated}, ${arr(d.neighbours)}, ${q(`/data/districts/${s.id}.topo.json`)});`,
    );
  }
}
lines.push("commit;");
const out = path.resolve(import.meta.dirname, "../supabase/seed.sql");
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${out} (${STATES.length} states, ${districtRows} districts)`);
